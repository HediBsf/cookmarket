async function upsertDish(sellerId: number, categoryId: number, data: {
  name: string;
  description: string;
  price: number;
  imageUrl: string;
  quantity: number;
  city: string;
  allergens?: string;
  preparationTime?: number;
}) {
  const existing = await prisma.dish.findFirst({
    where: { name: data.name, sellerId },
  });

  if (existing) {
    return prisma.dish.update({
      where: { id: existing.id },
      data: { ...data, categoryId, availability: true },
    });
  }

  return prisma.dish.create({
    data: { ...data, sellerId, categoryId, availability: true },
  });
}

async function upsertFormation(sellerId: number, data: {
  title: string;
  description: string;
  price: number;
  duration: string;
  level: string;
  imageUrl: string;
}) {
  const existing = await prisma.formation.findFirst({
    where: { title: data.title, sellerId },
  });

  if (existing) {
    return prisma.formation.update({
      where: { id: existing.id },
      data: { ...data, availability: true },
    });
  }

  return prisma.formation.create({
    data: { ...data, sellerId, availability: true },
  });
}

async function upsertRecipe(userId: number, categoryId: number, data: {
  title: string;
  description: string;
  imageUrl: string;
  ingredients: string;
  steps: string;
  preparationTime: number;
  cookingTime?: number;
  difficulty: string;
  servings?: number;
}) {
  const existing = await prisma.recipe.findFirst({
    where: { title: data.title, userId },
  });

  if (existing) {
    return prisma.recipe.update({
      where: { id: existing.id },
      data: { ...data, categoryId },
    });
  }

  return prisma.recipe.create({
    data: { ...data, userId, categoryId },
  });
}

